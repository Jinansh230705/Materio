const fs = require('fs').promises;
const path = require('path');

async function generate() {
  const webDir = path.join(__dirname, '..', 'oread', 'web');
  const viewerCssPath = path.join(webDir, 'viewer.css');
  const imagesDir = path.join(webDir, 'images');
  const outCssPath = path.join(webDir, 'icons-inline.css');

  const css = await fs.readFile(viewerCssPath, 'utf8');

  // Find CSS custom properties that reference images/*.svg
  const varRegex = /(--[a-zA-Z0-9-_]+)\s*:\s*url\((?:"|')?(images\/[a-zA-Z0-9_\-\.]+\.svg)(?:"|')?\)\s*;/g;
  const vars = new Map();
  let m;
  while ((m = varRegex.exec(css)) !== null) {
    const varName = m[1];
    const relPath = m[2];
    vars.set(varName, relPath);
  }

  if (vars.size === 0) {
    console.warn('No CSS variables referencing images/*.svg found in viewer.css');
  }

  const assignments = [];
  for (const [varName, relPath] of vars.entries()) {
    try {
      const svgPath = path.join(webDir, relPath.replace('images/', 'images/'));
      let svg = await fs.readFile(svgPath);
      // Base64 encode to be safe in CSS
      const data = svg.toString('base64');
      const uri = `url("data:image/svg+xml;base64,${data}")`;
      assignments.push(`  ${varName}: ${uri};`);
    } catch (err) {
      console.error('Failed to inline', relPath, err.message);
    }
  }

  const out = `/* This file is autogenerated by scripts/generate-oread-icons-css.js */\n:root {\n${assignments.join('\n')}\n}\n`;
  await fs.writeFile(outCssPath, out, 'utf8');
  console.log('Wrote', outCssPath);
}

generate().catch(err => {
  console.error(err);
  process.exit(1);
});
